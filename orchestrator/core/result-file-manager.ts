import { promises as fs } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';
import {
  StructuredAgentResult,
  ResultPaths,
  PreviousResults,
  WorkflowResultIndex,
  AgentResultEntry,
  AgentResult,
  TextSplitter
} from './types.js';
import { ServerLogger } from './server-logger.js';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

/**
 * Utility function to split long text into readable lines
 */
const splitIntoLines: TextSplitter = (text: string, maxLength = 100): string[] => {
  if (!text) return [];
  return text.split('\n').flatMap(line => {
    if (line.length <= maxLength) return [line];
    const chunks = [];
    for (let i = 0; i < line.length; i += maxLength) {
      chunks.push(line.slice(i, i + maxLength));
    }
    return chunks;
  });
};

/**
 * ResultFileManager handles the complete historical record of agent execution outputs.
 *
 * This class manages RESULT FILES (not handover files) which serve as the permanent
 * archive of what each agent produced. Result files include:
 * - Complete agent outputs and artifacts
 * - Performance metrics and timing data
 * - Human-readable summaries
 * - Embedded handover data for reference
 *
 * These files are used for:
 * - Audit trails and compliance
 * - Debugging and troubleshooting
 * - Performance analysis and optimization
 * - Historical workflow analysis
 *
 * For inter-agent communication, see HandoverChain class which manages
 * curated context transfer between agents.
 */
export class ResultFileManager {
  private readonly workflowsBaseDir: string;
  private logger?: ServerLogger;

  constructor(logger?: ServerLogger) {
    this.workflowsBaseDir = join(__dirname, '../state');
    this.logger = logger;
  }

  async initialize(): Promise<void> {
    await this.ensureDirectoryExists(this.workflowsBaseDir);
    await this.ensureDirectoryExists(join(this.workflowsBaseDir, 'active'));
    await this.ensureDirectoryExists(join(this.workflowsBaseDir, 'completed'));
  }

  /**
   * Write complete agent result to organized files for permanent archival.
   *
   * Creates a complete historical record including:
   * - result.json: Full structured agent output with all data and metadata
   * - summary.md: Human-readable summary for easy review
   * - artifacts/: Directory for any files generated by the agent
   *
   * These result files are separate from handover files and serve different purposes:
   * - Result files = Complete historical record for audit/debugging
   * - Handover files = Curated context for next agent communication
   *
   * @param workflowId - Unique workflow identifier
   * @param stepIndex - Agent's position in workflow sequence
   * @param agentName - Name of the agent that produced this result
   * @param result - Complete structured result with all agent outputs
   * @returns Paths to all created files and directories
   */
  async writeAgentResult(
    workflowId: string,
    stepIndex: number,
    agentName: string,
    result: StructuredAgentResult
  ): Promise<ResultPaths> {
    const workflowDir = this.getWorkflowDir(workflowId);
    const stepDirName = `${String(stepIndex).padStart(2, '0')}-${agentName}`;
    const resultDir = join(workflowDir, 'results', stepDirName);

    // Ensure directory structure exists
    await this.ensureDirectoryExists(resultDir);
    await this.ensureDirectoryExists(join(resultDir, 'artifacts'));

    const paths: ResultPaths = {
      resultDir,
      resultFile: join(resultDir, 'result.json'),
      artifactsDir: join(resultDir, 'artifacts')
    };

    // Process result for better readability
    const processedResult = this.processResultForReadability(result);

    // Write main result file with processed data
    await fs.writeFile(paths.resultFile, JSON.stringify(processedResult, null, 2));

    // Update workflow index
    await this.updateWorkflowIndex(workflowId, agentName, stepIndex, paths, result.status);

    if (this.logger) {
      this.logger.logWithContext('info', 'WORKFLOW', `Saved ${agentName} results to: ${resultDir}`);
    }
    return paths;
  }

  /**
   * Read previous agents' results for current agent
   */
  async readPreviousResults(
    workflowId: string,
    currentStep: number
  ): Promise<PreviousResults[]> {
    const workflowDir = this.getWorkflowDir(workflowId);
    const resultsDir = join(workflowDir, 'results');

    try {
      const entries = await fs.readdir(resultsDir, { withFileTypes: true });
      const previousResults: PreviousResults[] = [];

      for (const entry of entries) {
        if (!entry.isDirectory()) continue;

        const stepMatch = entry.name.match(/^(\d+)-(.+)$/);
        if (!stepMatch) continue;

        const stepIndex = parseInt(stepMatch[1]);
        if (stepIndex >= currentStep) continue;

        const agentName = stepMatch[2];
        const resultPath = join(resultsDir, entry.name);
        const resultFile = join(resultPath, 'result.json');

        try {
          const resultContent = await fs.readFile(resultFile, 'utf-8');
          const result = JSON.parse(resultContent) as StructuredAgentResult;

          previousResults.push({
            agent: agentName,
            stepIndex,
            resultPath,
            result,
            available: true
          });
        } catch (error) {
          if (this.logger) {
            this.logger.logWithContext('warn', 'WORKFLOW', `Could not read result for ${agentName} at step ${stepIndex}: ${error}`);
          }
          previousResults.push({
            agent: agentName,
            stepIndex,
            resultPath,
            result: {} as StructuredAgentResult,
            available: false
          });
        }
      }

      return previousResults.sort((a, b) => a.stepIndex - b.stepIndex);
    } catch (error) {
      if (this.logger) {
        this.logger.logWithContext('warn', 'WORKFLOW', `Could not read previous results for workflow ${workflowId}: ${error}`);
      }
      return [];
    }
  }

  /**
   * Get specific agent's result
   */
  async getAgentResult(
    workflowId: string,
    agentName: string
  ): Promise<StructuredAgentResult | null> {
    const workflowDir = this.getWorkflowDir(workflowId);
    const resultsDir = join(workflowDir, 'results');

    try {
      const entries = await fs.readdir(resultsDir, { withFileTypes: true });

      for (const entry of entries) {
        if (!entry.isDirectory()) continue;

        const stepMatch = entry.name.match(/^(\d+)-(.+)$/);
        if (!stepMatch || stepMatch[2] !== agentName) continue;

        const resultFile = join(resultsDir, entry.name, 'result.json');
        const resultContent = await fs.readFile(resultFile, 'utf-8');
        return JSON.parse(resultContent) as StructuredAgentResult;
      }
    } catch (error) {
      if (this.logger) {
        this.logger.logWithContext('warn', 'WORKFLOW', `Could not get result for agent ${agentName}: ${error}`);
      }
    }

    return null;
  }

  /**
   * Convert legacy AgentResult to StructuredAgentResult
   */
  convertLegacyResult(
    workflowId: string,
    stepIndex: number,
    agentName: string,
    legacyResult: AgentResult | { result: string; success: boolean },
    taskDescription?: string
  ): StructuredAgentResult {
    // Handle both old AgentResult format and new simplified format
    const result = typeof legacyResult === 'object' && 'result' in legacyResult ? legacyResult.result : (legacyResult as AgentResult).result || '';
    const success = typeof legacyResult === 'object' && 'success' in legacyResult ? legacyResult.success : (legacyResult as AgentResult).success;
    const error = (legacyResult as AgentResult).error;
    const duration = (legacyResult as AgentResult).duration;

    const structuredResult: StructuredAgentResult = {
      agent: agentName,
      timestamp: new Date().toISOString(),
      status: success ? 'completed' : 'failed',
      stepIndex,
      workflowId,
      output: {
        result: splitIntoLines(result || ''),
        success: success
      },
      metrics: {
        duration: duration || 0,
        filesCreated: 0
      }
    };

    // Only add optional fields if they have meaningful content
    if (result && result.trim()) {
      structuredResult.handover = {
        keyPoints: splitIntoLines(result, 200), // Longer lines for key points
        instructions: taskDescription || undefined
      };
    }

    return structuredResult;
  }

  /**
   * Create workflow directory structure
   */
  async createWorkflowDirectory(workflowId: string): Promise<string> {
    const workflowDir = this.getWorkflowDir(workflowId);

    await this.ensureDirectoryExists(workflowDir);
    await this.ensureDirectoryExists(join(workflowDir, 'results'));
    await this.ensureDirectoryExists(join(workflowDir, 'handover'));

    // Create initial index file
    const index: WorkflowResultIndex = {
      workflow: workflowId,
      agents: [],
      createdAt: new Date().toISOString(),
      updatedAt: new Date().toISOString()
    };

    await fs.writeFile(
      join(workflowDir, 'index.json'),
      JSON.stringify(index, null, 2)
    );

    if (this.logger) {
      this.logger.logWithContext('info', 'WORKFLOW', `Created workflow directory: ${workflowDir}`);
    }
    return workflowDir;
  }

  /**
   * Get all results for a workflow
   */
  async getWorkflowResults(workflowId: string): Promise<StructuredAgentResult[]> {
    const previousResults = await this.readPreviousResults(workflowId, 999);
    return previousResults
      .filter(pr => pr.available)
      .map(pr => pr.result);
  }

  /**
   * Move completed workflow to archive
   */
  async archiveWorkflowResults(workflowId: string): Promise<string> {
    const activeDir = join(this.workflowsBaseDir, 'active', workflowId);
    const archiveDir = join(this.workflowsBaseDir, 'completed', workflowId);

    try {
      // Create archive directory
      await this.ensureDirectoryExists(dirname(archiveDir));

      // Move the entire workflow directory
      await fs.rename(activeDir, archiveDir);

      if (this.logger) {
        this.logger.logWithContext('info', 'WORKFLOW', `Archived workflow results: ${workflowId}`);
      }
      return archiveDir;
    } catch (error) {
      if (this.logger) {
        this.logger.logWithContext('warn', 'WORKFLOW', `Failed to archive workflow ${workflowId}: ${error}`);
      }
      throw error;
    }
  }

  private getWorkflowDir(workflowId: string): string {
    return join(this.workflowsBaseDir, 'active', workflowId);
  }

  private async updateWorkflowIndex(
    workflowId: string,
    agentName: string,
    stepIndex: number,
    paths: ResultPaths,
    status: string
  ): Promise<void> {
    const workflowDir = this.getWorkflowDir(workflowId);
    const indexFile = join(workflowDir, 'index.json');

    let index: WorkflowResultIndex;

    try {
      const indexContent = await fs.readFile(indexFile, 'utf-8');
      index = JSON.parse(indexContent);
    } catch (error) {
      index = {
        workflow: workflowId,
        agents: [],
        createdAt: new Date().toISOString(),
        updatedAt: new Date().toISOString()
      };
    }

    // Update or add agent entry
    const existingIndex = index.agents.findIndex(a => a.name === agentName && a.step === stepIndex);
    const agentEntry: AgentResultEntry = {
      name: agentName,
      step: stepIndex,
      resultPath: paths.resultDir,
      status: status as any,
      artifacts: await this.getArtifactsList(paths.artifactsDir),
      timestamp: new Date().toISOString()
    };


    if (existingIndex >= 0) {
      index.agents[existingIndex] = agentEntry;
    } else {
      index.agents.push(agentEntry);
    }

    index.updatedAt = new Date().toISOString();

    await fs.writeFile(indexFile, JSON.stringify(index, null, 2));
    if (this.logger) {
this.logger?.logWithContext('info', 'WORKFLOW', `Updated workflow index for ${workflowId}`);
    }
  }

  private async getArtifactsList(artifactsDir: string): Promise<string[]> {
    try {
      const entries = await fs.readdir(artifactsDir);
      return entries.filter(entry => !entry.startsWith('.'));
    } catch {
      return [];
    }
  }

  /**
   * Process agent result for better readability by splitting long strings into lines
   * and removing empty optional fields
   */
  private processResultForReadability(result: StructuredAgentResult): StructuredAgentResult {
    // Split output result into lines for better readability
    const resultText = typeof result.output === 'object' && result.output.result
      ? result.output.result
      : result.output?.toString() || '';

    const processedOutput = {
      result: splitIntoLines(String(resultText)),
      success: result.output?.success ?? true
    };

    // Create clean result object, only including non-empty optional fields
    const cleanResult: StructuredAgentResult = {
      agent: result.agent,
      timestamp: result.timestamp,
      status: result.status,
      stepIndex: result.stepIndex,
      workflowId: result.workflowId,
      output: processedOutput,
      metrics: result.metrics
    };

    // Only add artifacts if they exist
    if (result.artifacts && Object.keys(result.artifacts).length > 0) {
      cleanResult.artifacts = result.artifacts;
    }

    // Only add handover data if it has meaningful content
    if (result.handover) {
      const handover: any = {};

      if (result.handover.keyPoints && result.handover.keyPoints.length > 0) {
        handover.keyPoints = result.handover.keyPoints;
      }

      if (result.handover.instructions && result.handover.instructions.trim() !== '') {
        handover.instructions = result.handover.instructions;
      }

      if (result.handover.dependencies && result.handover.dependencies.length > 0) {
        handover.dependencies = result.handover.dependencies;
      }

      if (result.handover.data && Object.keys(result.handover.data).length > 0) {
        handover.data = result.handover.data;
      }

      // Only add handover if it has any content
      if (Object.keys(handover).length > 0) {
        cleanResult.handover = handover;
      }
    }

    return cleanResult;
  }

  private async ensureDirectoryExists(dir: string): Promise<void> {
    try {
      await fs.access(dir);
    } catch {
      await fs.mkdir(dir, { recursive: true });
    }
  }
}